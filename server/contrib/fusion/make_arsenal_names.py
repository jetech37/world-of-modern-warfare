#!/usr/bin/env python3
"""Azeroth Warfare: write the server's arsenal names table from the client's data file.

    make_arsenal_names.py [client/assets/arsenal_names.json [server/src/fusion/src/ArsenalTable.cpp]]

The names and origins of every weapon, attachment, camo, perk, deathstreak and killstreak live in
one file the client reads (client/assets/arsenal_names.json). The server's rules carry the same
table compiled in (fusion/Arsenal.h), so chat lines and achievement texts use the same names;
this script writes it, and the fusion test ArsenalTests fails when the two drift apart. Run it
after editing the names. Paths default to the monorepo's own.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
KINDS = [("weapons", "kWeapons"), ("attachments", "kAttachments"), ("camos", "kCamos"),
         ("perks", "kPerks"), ("killstreaks", "kKillstreaks")]


def c_string(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            for b in ch.encode("utf-8"):
                out.append("\\x%02x\" \"" % b)
    return '"' + "".join(out) + '"'


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "client", "assets", "arsenal_names.json")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "server", "src", "fusion", "src", "ArsenalTable.cpp")
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    lines = [
        "/*",
        " * Azeroth Warfare: the fusion rules. GPL-2.0-or-later, see Common.h.",
        " *",
        " * Generated by server/contrib/fusion/make_arsenal_names.py from client/assets/arsenal_names.json;",
        " * edit the JSON and run the script, not this file (ArsenalTests checks they agree).",
        " */",
        "",
        '#include "fusion/Arsenal.h"',
        "",
        "#include <iterator>",
        "",
        "namespace Fusion::Arsenal",
        "{",
        "    namespace",
        "    {",
    ]
    for key, var in KINDS:
        lines.append("        Lore const %s[] = {" % var)
        for k, v in data[key].items():
            lines.append("            {%s, %s," % (c_string(k), c_string(v["name"])))
            lines.append("                %s}," % c_string(v["origin"]))
        lines.append("        };")
        if var != KINDS[-1][1]:
            lines.append("")
    lines += [
        "    }",
        "",
        "    Lore const* Table(Kind kind, size_t& count)",
        "    {",
        "        switch (kind)",
        "        {",
    ]
    for (key, var), kind in zip(KINDS, ["Weapon", "Attachment", "Camo", "Perk", "Killstreak"]):
        lines.append("            case Kind::%s: count = std::size(%s); return %s;" % (kind, var, var))
    lines += [
        "            case Kind::Count: break;",
        "        }",
        "        count = 0;",
        "        return nullptr;",
        "    }",
        "}",
        "",
    ]
    text = "\n".join(lines)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%s)" % (dst, ", ".join("%d %s" % (len(data[k]), k) for k, _ in KINDS)))


if __name__ == "__main__":
    main()
