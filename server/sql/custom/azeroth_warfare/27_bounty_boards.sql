-- World of Modern Warfare: bounty boards (server/src/game/Fusion/FusionBounties.cpp, the rules in
-- server/src/fusion/include/fusion/Bounties.h). World DB; safe to apply again: the two tables are
-- this file's own and are made afresh, and each block clears its own id range first.
--
-- Reserved ranges:
--   gameobject_template.entry    191200 (the Bounty Board)
--   gameobject.guid              4192001-4192099 (the boards)
--   quest ids                    95000-97999: made by the server at startup, never in quest_template
--
-- A Bounty Board stands in the towns and outposts of the open-world zones. Each zone's boards post
-- up to five bounties a day, generated by the server from the zone's own creature spawns and drops
-- (aw_bounty_zone gives each zone its level band and a fixed slot, which fixes its quest ids).
-- A board is placed beside an anchor creature of its town (the flight master, who stands outdoors
-- in nearly every town): `dx`/`dy` yards from it, facing it, on its height. An anchor that is not
-- spawned leaves its board out (and its row is dropped), so a wrong entry never puts a board in a
-- strange place unnoticed: the server also logs a board that does not stand in its zone.
-- VERIFY every board in game (.go object): the height is the anchor's, and a spot on a slope or a
-- platform edge may want nudging.

-- ── The board ───────────────────────────────────────────────────────────────────────────────────
-- Type 2 (questgiver) with no quests of its own: the script opens the bounty window instead. The
-- model is vanilla's Wanted Board (2713, the Stormwind and Lakeshire notice boards); should that
-- template be missing, the Wanted Poster's display (17).
DELETE FROM `gameobject_template` WHERE `entry` = 191200;
INSERT INTO `gameobject_template` (`entry`, `patch`, `type`, `displayId`, `name`, `faction`, `flags`, `size`,
  `data0`, `data1`, `data2`, `data3`, `script_name`)
SELECT 191200, 0, 2, t.`displayId`, 'Bounty Board', 35, 0, t.`size`, 0, 0, 0, 0, 'go_fusion_bounty_board'
FROM `gameobject_template` t WHERE t.`entry` = 2713 ORDER BY t.`patch` DESC LIMIT 1;
INSERT IGNORE INTO `gameobject_template` (`entry`, `patch`, `type`, `displayId`, `name`, `faction`, `flags`, `size`,
  `data0`, `data1`, `data2`, `data3`, `script_name`) VALUES
(191200, 0, 2, 17, 'Bounty Board', 35, 0, 1, 0, 0, 0, 0, 'go_fusion_bounty_board');

-- ── The zones ───────────────────────────────────────────────────────────────────────────────────
-- `zone` is the AreaTable id; `slot` (0-199) places the zone's quest ids, so keep a zone's slot
-- once given (a new zone takes a new slot). The band is the zone's levels; targets a level below
-- or two above still count.
DROP TABLE IF EXISTS `aw_bounty_zone`;
CREATE TABLE `aw_bounty_zone` (
  `zone` int(10) unsigned NOT NULL,
  `slot` smallint(5) unsigned NOT NULL,
  `min_level` tinyint(3) unsigned NOT NULL,
  `max_level` tinyint(3) unsigned NOT NULL,
  `name` varchar(64) NOT NULL DEFAULT '' COMMENT 'for reading this table; the server names zones from AreaTable',
  PRIMARY KEY (`zone`),
  UNIQUE KEY `slot` (`slot`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='WOMW bounty boards: the zones that post bounties';

