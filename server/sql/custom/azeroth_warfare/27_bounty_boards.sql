  `rep_faction` int(10) unsigned NOT NULL DEFAULT '0',
  `anchor` mediumint(8) unsigned NOT NULL,
  `dx` float NOT NULL DEFAULT '4',
  `dy` float NOT NULL DEFAULT '0',
  PRIMARY KEY (`guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='WOMW bounty boards: where the boards stand';

