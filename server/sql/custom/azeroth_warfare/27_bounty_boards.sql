-- The spawns: each beside its anchor's first spawn of the server's patch (WowPatch = 10), facing it.
DELETE FROM `gameobject` WHERE `guid` BETWEEN 4192001 AND 4192099;
INSERT INTO `gameobject` (`guid`, `id`, `map`, `position_x`, `position_y`, `position_z`, `orientation`,
  `rotation0`, `rotation1`, `rotation2`, `rotation3`, `spawntimesecsmin`, `spawntimesecsmax`, `animprogress`, `state`)
SELECT b.`guid`, 191200, c.`map`, c.`position_x` + b.`dx`, c.`position_y` + b.`dy`, c.`position_z`,
  o.`o`, 0, 0, SIN(o.`o` / 2), COS(o.`o` / 2), 120, 120, 100, 1
FROM `aw_bounty_board` b
JOIN (SELECT `id`, MIN(`guid`) AS `guid` FROM `creature`
      WHERE `patch_min` <= 10 AND `patch_max` >= 10 GROUP BY `id`) a ON a.`id` = b.`anchor`
JOIN `creature` c ON c.`guid` = a.`guid`
JOIN (SELECT `guid`, IF(ATAN2(-`dy`, -`dx`) < 0, ATAN2(-`dy`, -`dx`) + 2 * PI(), ATAN2(-`dy`, -`dx`)) AS `o`
      FROM `aw_bounty_board`) o ON o.`guid` = b.`guid`;

-- A board whose anchor is not spawned: no board, and no row for the server to look for.
DELETE b FROM `aw_bounty_board` b LEFT JOIN `gameobject` g ON g.`guid` = b.`guid` WHERE g.`guid` IS NULL;
