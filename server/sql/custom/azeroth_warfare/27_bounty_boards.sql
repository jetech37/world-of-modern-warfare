-- ── The boards ──────────────────────────────────────────────────────────────────────────────────
-- `team`: 0 anyone (a neutral town), 1 Alliance, 2 Horde. `rep_faction`: the Faction.dbc id a
-- turned-in bounty gives reputation with (0 none). `anchor`: the creature entry the board stands
-- beside (its first spawn).
DROP TABLE IF EXISTS `aw_bounty_board`;
