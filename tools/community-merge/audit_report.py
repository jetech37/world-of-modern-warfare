"""Writes design/COMMUNITY_QUEST_AUDIT.md from a quest_audit.Audit run."""
from collections import defaultdict

# Filled in by community_fixes.write() when it runs first.
FIXES = {"fixed": {}, "hidden": {}, "boss_ai": [], "cpp": []}


def esc(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def write(au, scripts, path):
    res, Q = au.res, au.quests
    n = defaultdict(int)
    for v in res.values():
        n[v["status"]] += 1
    fixed, hidden = FIXES["fixed"], FIXES["hidden"]
    L = []
    L.append("# Community content: quest and script audit (PRIVATE)\n")
    L.append("Private notes, like `COMMUNITY_MERGE.md`: never in the public tree; say \"the community client\".\n")
    L.append("Generated by `python -I tools/community-merge/quest_audit.py --sql "
             "server/sql/custom/azeroth_warfare/81_community_fixes.sql` against the local world DB "
             "(read-only). Rerun after any re-import.\n")
    L.append("## Summary\n")
    total = len(res)
    after_ok = sum(1 for k, v in res.items() if v["status"] == "ok" or k in fixed)
    L.append(f"- Imported quests audited: **{total}**.")
    L.append(f"- Completable from data as imported: **{n['ok']}** clean, **{n['risk']}** completable but touching "
             f"something whose C++ script we lack (giver gossip, target behaviour, item script) - playable, may feel off.")
    L.append(f"- Blocked as imported: **{n['broken']}**. Of those, **{len(fixed)}** fixed in data by "
             f"`81_community_fixes.sql` and **{len(hidden)}** hidden (an always-false `RequiredCondition`, "
             f"condition {au_hide(au)}; no rows deleted). Undo a hide by setting `RequiredCondition` back to 0.")
    L.append(f"- Working after the fixes: **{after_ok + n['risk']}** of {total} offered to players "
             f"({after_ok} clean or fixed, {n['risk']} at risk).")
    L.append(f"- Missing C++ scripts: {sum(1 for s in scripts if s['kind']=='creature')} creatures, "
             f"{sum(1 for s in scripts if s['kind']=='gameobject')} objects, "
             f"{sum(1 for s in scripts if s['kind']=='item')} items, {len(au.noscript['map'])} instance maps.")
    L.append(f"- Bosses given EventAI: **{len(FIXES['boss_ai'])}** (table below).\n")

    reasons = defaultdict(int)
    for v in res.values():
        for b in v["block"]:
            key = b.split(" (")[0].split(":")[0]
            for w in ("target creature", "target object", "required item", "prerequisite quest", "objective spell"):
                if b.startswith(w):
                    key = w + (" cannot be completed" if "cannot" in b else " missing/unreachable")
            reasons[key] += 1
    L.append("### Why quests were blocked (a quest can have several reasons)\n")
    L.append("| reason | quests |\n|---|---:|")
    for k, c in sorted(reasons.items(), key=lambda x: -x[1]):
        L.append(f"| {esc(k)} | {c} |")
    L.append("")

    zones = defaultdict(list)
    for k, v in res.items():
        zones[v["zone"]].append(k)
    L.append("### Per zone\n")
    L.append("| zone | quests | ok | at risk | broken | fixed | hidden |\n|---|---:|---:|---:|---:|---:|---:|")
    for z in sorted(zones, key=lambda z: -len(zones[z])):
        ks = zones[z]
        c = defaultdict(int)
        for k in ks:
            c[res[k]["status"]] += 1
        L.append(f"| {esc(z)} | {len(ks)} | {c['ok']} | {c['risk']} | {c['broken']} | "
                 f"{sum(1 for k in ks if k in fixed)} | {sum(1 for k in ks if k in hidden)} |")
    L.append("")

    L.append("## Boss EventAI added\n")
    L.append("| creature | name | level | where | spells | phases |\n|---:|---|---:|---|---|---|")
    for b in FIXES["boss_ai"]:
        L.append(f"| {b['id']} | {esc(b['name'])} | {b['level']} | {esc(b['where'])} | {esc(b['spells'])} | {esc(b['phases'])} |")
    L.append("")

    L.append("## Needs C++ (top 10, for a later pass)\n")
    L.append("| # | what | where | needs |\n|---:|---|---|---|")
    for i, c in enumerate(FIXES["cpp"], 1):
        L.append(f"| {i} | {esc(c['what'])} | {esc(c['where'])} | {esc(c['needs'])} |")
    L.append("")

    L.append("## Missing C++ scripts, ranked\n")
    L.append("Tiers: 1 quest-relevant (giver, ender, target or item of an imported quest), 2 dungeon boss, "
             "3 rare, 4 flavour. `AI` = EventAI events now on it (after the fixes count separately above).\n")
    L.append("| tier | kind | id | name | script | level | where | spawns | quests | AI |\n|---|---|---:|---|---|---:|---|---:|---|---:|")
    for s in scripts:
        qs = ", ".join(str(x) for x in s["quests"][:6]) + (" ..." if len(s["quests"]) > 6 else "")
        L.append(f"| {s['tier']} | {s['kind']} | {s['id']} | {esc(s['name'])} | `{s['script']}` | {s['level']} | "
                 f"{esc(s['where'])} | {s['spawns']} | {qs} | {s['has_ai']} |")
    L.append("")
    if au.noscript["map"]:
        L.append("Instance scripts lacking (doors, encounter state, boss gating): " +
                 ", ".join(f"{m} `{n}`" for m, n in sorted(au.noscript["map"].items())) + ".\n")

    L.append("## Quests by zone\n")
    L.append("Status: ok, risk (completable, touches a missing script), broken. Action: fixed / hidden / -.\n")
    for z in sorted(zones):
        L.append(f"### {esc(z)}\n")
        L.append("| quest | title | lvl | status | action | details |\n|---:|---|---:|---|---|---|")
        for k in sorted(zones[z], key=lambda k: (int(Q[k]["QuestLevel"] or 0), k)):
            v = res[k]
            act = "fixed: " + fixed[k] if k in fixed else ("hidden" if k in hidden else "-")
            det = "; ".join(v["block"] + v["risk"] + v["notes"])
            L.append(f"| {k} | {esc(Q[k]['Title'])} | {Q[k]['QuestLevel']} | {v['status']} | {esc(act)} | {esc(det)} |")
        L.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


def au_hide(au):
    import quest_audit
    return quest_audit.HIDE_CONDITION
