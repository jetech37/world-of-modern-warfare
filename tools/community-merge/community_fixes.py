"""Data fixes for the imported community content, written as one idempotent SQL file.

Called by quest_audit.py --sql. Reads a scratch copy of their world DB (see COMMUNITY_MERGE.md,
pipeline step 1) for what the import left out:

1. Quest givers/enders that are *our* (stock) creatures or objects: the import only took the
   relations of entries it imported, so a community quest handed out by a stock NPC lost its giver.
2. Quest-item drops on our stock creatures and objects (their loot rows for an item we imported).

Then it re-audits with those fixes, hides every quest that is still blocked (an always-false
RequiredCondition; no rows are deleted) and gives EventAI to the dungeon and zone bosses whose
C++ script we lack and that would only melee.
"""
import os
import re
from collections import defaultdict

import audit_report
from cdb import query
from quest_audit import HIDE_CONDITION, I, INSTANCE_MAPS

STOCK_KITS = {
    # element: (low-level spells <= 40, high-level spells > 40) - stock 1.12 creature spells
    "frost": ([9672, 11831], [15530, 11831]),
    "nature": ([12058, 8078], [12058, 8078]),
    "fire": ([15039, 11829], [15039, 11829]),
    "shadow": ([9613, 8282], [20825, 8282]),
    "melee": ([15496, 11428], [15496, 13737]),
}
ELEMENT_WORDS = {
    "frost": "frost frigid ice snow hail winter cold tide sea hydro water wave",
    "nature": "storm thunder wind lightning sky",
    "fire": "fire flame ember burn blaze ash magma",
    "shadow": "shadow death dark bone crypt void bishop necro doom grave soul spectre spirit",
}
CASTER_WORDS = ("priest", "bishop", "speaker", "librarian", "magister", "mage", "shaman", "druid", "warlock",
                "necromancer", "cultist", "doomcaller", "subjugator", "hydromancer", "sorcer", "seer", "oracle",
                "mystic", "conjurer", "witch", "lady", "priestess", "spirit", "spectre")
GENERIC = {"the", "lord", "lady", "of", "iv", "duke", "chieftain", "champion", "elder", "high", "grand", "dark",
           "arch", "king", "regent", "sir", "captain", "commander", "general", "keeper", "engineer", "foreman",
           "senior", "librarian", "deathlord", "subjugator", "bonespeaker", "primordial", "glutton", "whacked",
           "frigid", "storm", "guardian", "torn", "heart"}
ENRAGE = 8599
CHESS = {"King", "Queen", "Rook", "Bishop", "Knight", "Pawn"}
FEAR = 16508


class Theirs:
    def __init__(self, port):
        self.port = port
        # The scratch copy of the community repack's world schema (same name as db_import.py --theirs).
        self.db = os.environ.get("AW_THEIRS_DB")
        if not self.db:
            raise SystemExit("set AW_THEIRS_DB to the name of the scratch copy of their world schema")

    def q(self, sql):
        return query(sql, db=self.db, port=self.port)


def sql_list(xs):
    return ",".join(str(int(x)) for x in sorted(set(xs))) or "0"


def write(au, path, port):
    th = Theirs(port)
    rev = {k: {v: o for o, v in m.items()} for k, m in au.ids.items()}
    their_q = {rev["quest"][q]: q for q in au.Q}
    C = lambda e: au.ids["creature"].get(e, e)
    G = lambda e: au.ids["gameobject"].get(e, e)
    IT = lambda e: au.ids["item"].get(e, e)
    out = ["-- 81_community_fixes.sql: data fixes for the imported community content.",
           "-- Generated by tools/community-merge/quest_audit.py --sql (see design/COMMUNITY_QUEST_AUDIT.md).",
           "-- Idempotent; applies after 80_community_zones.sql. Never names the community client's developers.",
           "-- Hidden quests: RequiredCondition = %d (never true). Undo: set it back to 0." % HIDE_CONDITION, ""]
    fixed_why = defaultdict(list)

    # 1. givers and enders --------------------------------------------------------------------
    orig = au.res
    before = {k for k, v in au.res.items() if v["status"] == "broken"}
    rel_rows = defaultdict(list)
    need_flag = set()  # stock NPCs that now give or take a quest but lack the quest-giver flag
    for t, kind, store, okf, M in (("creature", "questrelation", au.c_start, au.creature_ok, C),
                                    ("creature", "involvedrelation", au.c_end, au.creature_ok, C),
                                    ("gameobject", "questrelation", au.g_start, au.go_ok, G),
                                    ("gameobject", "involvedrelation", au.g_end, au.go_ok, G)):
        for r in th.q(f"select id, quest from {t}_{kind} where quest in ({sql_list(their_q)})"):
            q = their_q[I(r["quest"])]
            e = M(I(r["id"]))
            if q not in before or e in store.get(q, ()):
                continue
            ok = okf(e)[0]
            if not ok:
                continue
            if t == "creature" and not I(au.ct[e]["npc_flags"]) & 2:
                need_flag.add(e)
            store[q].add(e)
            rel_rows[f"{t}_{kind}"].append((e, q))
            fixed_why[q].append(f"{'giver' if kind == 'questrelation' else 'ender'} {t} {e} restored")

    # 2. quest-item loot on stock creatures / objects -------------------------------------------
    loot_rows = []
    need_items = set()
    for q in before:
        qq = au.quests[q]
        for i in range(1, 5):
            it = I(qq[f"ReqItemId{i}"])
            if it and it in au.it and not any(s[2] for s in au.item_sources(it)):
                need_items.add(it)
    their_items = {rev["item"].get(i, i): i for i in need_items}
    if their_items:
        ct_by_loot = defaultdict(set)
        for r in th.q(f"select entry, loot_id from creature_template where loot_id in "
                      f"(select entry from creature_loot_template where item in ({sql_list(their_items)}))"):
            ct_by_loot[I(r["loot_id"])].add(I(r["entry"]))
        for r in th.q(f"select entry,item,ChanceOrQuestChance ch,groupid,mincountOrRef mc,maxcount from creature_loot_template "
                      f"where item in ({sql_list(their_items)}) and mincountOrRef > 0"):
            item = their_items[I(r["item"])]
            for tc in ct_by_loot.get(I(r["entry"]), ()):
                c = C(tc)
                if c not in au.ct or not au.creature_ok(c)[0]:
                    continue
                lid = I(au.ct[c]["loot_id"])
                if not lid:
                    continue
                if item in au.loot["creature_loot_template"].get(lid, set()):
                    continue
                loot_rows.append(("creature_loot_template", lid, item, float(r["ch"]), I(r["mc"]), I(r["maxcount"]) or 1, c))
                au.loot["creature_loot_template"].setdefault(lid, set()).add(item)
                au._inv[item].append(("creature_loot_template", lid))
        go_by_loot = defaultdict(set)
        for r in th.q(f"select entry, data1 from gameobject_template where type in (3,25) and data1 in "
                      f"(select entry from gameobject_loot_template where item in ({sql_list(their_items)}))"):
            go_by_loot[I(r["data1"])].add(I(r["entry"]))
        for r in th.q(f"select entry,item,ChanceOrQuestChance ch,groupid,mincountOrRef mc,maxcount from gameobject_loot_template "
                      f"where item in ({sql_list(their_items)}) and mincountOrRef > 0"):
            item = their_items[I(r["item"])]
            for tg in go_by_loot.get(I(r["entry"]), ()):
                g = G(tg)
                if g not in au.gt or not au.go_ok(g)[0] or I(au.gt[g]["type"]) not in (3, 25):
                    continue
                lid = I(au.gt[g]["data1"])
                if not lid or item in au.loot["gameobject_loot_template"].get(lid, set()):
                    continue
                loot_rows.append(("gameobject_loot_template", lid, item, float(r["ch"]), I(r["mc"]), I(r["maxcount"]) or 1, g))
                au.loot["gameobject_loot_template"].setdefault(lid, set()).add(item)
                au._inv[item].append(("gameobject_loot_template", lid))
    for tbl, lid, item, ch, mc, mx, owner in loot_rows:
        for q in before:
            if any(I(au.quests[q][f"ReqItemId{i}"]) == item for i in range(1, 5)):
                fixed_why[q].append(f"item {item} drop added to {tbl.split('_')[0]} {owner}")

    # 3. re-audit; hide what is still blocked -------------------------------------------------
    after = au.evaluate()
    hidden = {}
    # hide iteratively: hiding a quest blocks quests that need it (already propagated by evaluate)
    for q, v in after.items():
        if v["status"] == "broken":
            hidden[q] = "; ".join(v["block"])
    fixed = {q: "; ".join(sorted(set(fixed_why[q]))) for q in before if after[q]["status"] != "broken"}
    au.res_after = after
    au.res = orig

    # 4. boss EventAI -------------------------------------------------------------------------
    bosses = pick_bosses(au)
    ai_events, ai_scripts, boss_info = build_boss_ai(au, bosses)

    # ---- SQL ----
    out.append("-- 1. Quest givers and enders that are stock NPCs/objects (relations the import left out).")
    for t, rs in sorted(rel_rows.items()):
        if rs:
            out.append(f"INSERT IGNORE INTO `{t}` (`id`, `quest`, `patch_min`, `patch_max`) VALUES")
            out.append(",\n".join(f"({e}, {q}, 0, 10)" for e, q in sorted(set(rs))) + ";")
    if need_flag:
        out.append("-- Their quest-giver flag (stock NPCs that only had gossip).")
        out.append(f"UPDATE `creature_template` SET `npc_flags` = `npc_flags` | 2 WHERE `entry` IN ({sql_list(need_flag)});")
    out.append("")
    out.append("-- 2. Quest-item drops on stock creatures and objects (from the community client's loot).")
    for tbl in ("creature_loot_template", "gameobject_loot_template"):
        rs = sorted({(lid, item, ch, mc, mx) for t, lid, item, ch, mc, mx, _ in loot_rows if t == tbl})
        if rs:
            cols = "`entry`, `item`, `ChanceOrQuestChance`, `groupid`, `mincountOrRef`, `maxcount`, `condition_id`"
            if tbl == "creature_loot_template":
                cols += ", `patch_min`, `patch_max`"
                vals = [f"({a}, {b}, {c:g}, 0, {max(1, d)}, {max(1, e)}, 0, 0, 10)" for a, b, c, d, e in rs]
            else:
                vals = [f"({a}, {b}, {c:g}, 0, {max(1, d)}, {max(1, e)}, 0)" for a, b, c, d, e in rs]
            out.append(f"INSERT IGNORE INTO `{tbl}` ({cols}) VALUES")
            out.append(",\n".join(vals) + ";")
    out.append("")
    out.append("-- 3. Quests that cannot be completed with data alone: hidden behind a never-true condition.")
    out.append(f"INSERT IGNORE INTO `conditions` (`condition_entry`, `type`, `value1`, `value2`, `value3`, `value4`, `flags`) "
               f"VALUES ({HIDE_CONDITION}, 15, 100, 1, 0, 0, 0);")
    hl = sorted(hidden)
    for i in range(0, len(hl), 200):
        out.append(f"UPDATE `quest_template` SET `RequiredCondition` = {HIDE_CONDITION} WHERE `entry` IN ("
                   + ",".join(str(x) for x in hl[i:i + 200]) + ");")
    out.append("")
    out.append("-- 4. EventAI for dungeon and zone bosses whose C++ script we lack (spells + health phases).")
    ents = sorted({b["id"] for b in boss_info})
    if ents:
        out.append(f"UPDATE `creature_template` SET `ai_name` = 'EventAI' WHERE `entry` IN ({sql_list(ents)});")
        ecols = ["id", "creature_id", "condition_id", "event_type", "event_inverse_phase_mask", "event_chance", "event_flags",
                 "event_param1", "event_param2", "event_param3", "event_param4", "action1_script", "action2_script",
                 "action3_script", "comment"]
        out.append("INSERT IGNORE INTO `creature_ai_events` (" + ", ".join(f"`{c}`" for c in ecols) + ") VALUES")
        out.append(",\n".join("(" + ", ".join(sqlv(e[c]) for c in ecols) + ")" for e in ai_events) + ";")
        scols = ["id", "delay", "priority", "command", "datalong", "datalong2", "target_type", "data_flags", "comments"]
        for s in ai_scripts:
            out.append("INSERT INTO `creature_ai_scripts` (" + ", ".join(f"`{c}`" for c in scols) + ") SELECT "
                       + ", ".join(sqlv(s[c]) for c in scols)
                       + f" FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM `creature_ai_scripts` WHERE `id` = {s['id']} "
                       f"AND `priority` = {s['priority']});")
    out.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    audit_report.FIXES.update(fixed=fixed, hidden=hidden, boss_ai=boss_info, cpp=cpp_list(au, boss_info))


def sqlv(v):
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"
    return str(v)


# ---- bosses ----------------------------------------------------------------------------------
def pick_bosses(au):
    """Dungeon bosses (rank 1/3 single spawns on 800-822 lacking their script) and the zone bosses of
    Gilneas and Tel'Abim (elite/rare script-less creatures there) that have no EventAI events and no
    spell list."""
    out = []
    for e, name in au.noscript["creature"].items():
        t = au.ct.get(e)
        if not t or au.ai_creatures.get(e) or I(t["spell_list_id"]):
            continue
        sp = au.reachable(au.c_spawn.get(e, []))
        if not sp:
            continue
        rank = I(t["rank"])
        maps = {s[0] for s in sp}
        zone = au.zone_at(*sp[0])
        boss_name = name.startswith("boss_")
        if maps & INSTANCE_MAPS and (rank in (1, 3)) and (boss_name or len(sp) <= 2):
            out.append((e, zone))
        elif zone in ("Gilneas", "Tel'Abim") and rank in (1, 2, 3, 4) and I(t["faction"]) not in (35,):
            out.append((e, zone))
    # Zone bosses of Gilneas and Tel'Abim without a script name too: elite/rare unique spawns with no AI.
    have = {b[0] for b in out}
    for e, t in au.ct.items():
        if e in have or e not in au.C or au.ai_creatures.get(e) or I(t["spell_list_id"]) or I(t["faction"]) == 35:
            continue
        sp = au.reachable(au.c_spawn.get(e, []))
        if sp and len(sp) <= 2 and I(t["rank"]) in (1, 2, 3, 4) and au.zone_at(*sp[0]) in ("Gilneas", "Tel'Abim"):
            out.append((e, au.zone_at(*sp[0])))
    # The Karazhan chess pieces are an event, not bosses: leave them for C++.
    return [b for b in out if au.ct[b[0]]["name"] not in CHESS]


def build_boss_ai(au, bosses):
    sp_rows = {I(r["entry"]): r for r in query(
        "select entry,name,spellLevel,attributes,effect1,effectImplicitTargetA1 ta,effectApplyAuraName1 a1,"
        "rangeIndex,castingTimeIndex from spell_template")}
    imported = [s for e, s in sp_rows.items() if e in au.SP and not I(s["attributes"]) & 0x40
                and I(s["effect1"]) in (2, 6, 9, 10) and I(s["spellLevel"]) > 0]
    events, scripts, info = [], [], []
    for e, zone in sorted(bosses, key=lambda b: I(au.ct[b[0]]["level_max"])):
        t = au.ct[e]
        name, lvl = t["name"], I(t["level_max"])
        low = name.lower()
        toks = {w for w in re.findall(r"[a-z']+", low) if len(w) >= 4 and w not in GENERIC}
        own = []
        for s in imported:
            words = set(re.findall(r"[a-z']+", s["name"].lower().replace("'s", "")))
            if toks & {w.replace("'s", "") for w in words} and abs(I(s["spellLevel"]) - lvl) <= 25:
                own.append(I(s["entry"]))
        own = sorted(set(own))[:2]
        element = next((el for el, ws in ELEMENT_WORDS.items() if any(w in low for w in ws.split())), None)
        caster = I(t["unit_class"]) == 8 or any(w in low for w in CASTER_WORDS)
        kit = STOCK_KITS[element or ("shadow" if caster else "melee")][0 if lvl <= 40 else 1]
        spells = own + [s for s in kit if s not in own]
        if element and not caster:  # an elemental melee boss: one element spell, then melee kit
            spells = own + [kit[0]] + STOCK_KITS["melee"][0 if lvl <= 40 else 1]
        spells = [s for s in spells if s in sp_rows][:4]
        n = 0
        base = e * 100 + 90

        def ev(etype, mask, flags, p, script, comment):
            nonlocal n
            eid = base + n
            n += 1
            events.append(dict(id=eid, creature_id=e, condition_id=0, event_type=etype, event_inverse_phase_mask=mask,
                               event_chance=100, event_flags=flags, event_param1=p[0], event_param2=p[1], event_param3=p[2],
                               event_param4=p[3], action1_script=script, action2_script=0, action3_script=0,
                               comment=f"{name} - {comment} (community fixes)"))

        def cast(sid, spell):
            s = sp_rows[spell]
            self_cast = I(s["ta"]) in (1, 21, 22) or I(s["effect1"]) == 10
            scripts.append(dict(id=sid, delay=0, priority=0, command=15, datalong=spell, datalong2=0,
                                target_type=8 if self_cast else 1, data_flags=0,
                                comments=f"{name} - Cast {s['name']}"))
        phases = []
        for i, spell in enumerate(spells):
            sid = e * 100 + 70 + i
            cast(sid, spell)
            # first two spells from the pull; the rest only in phase 1 (below 50%)
            mask = 0 if i < 2 else 1
            init = (3000 + 2000 * i, 7000 + 2000 * i)
            rep = (9000 + 3000 * i, 15000 + 3000 * i)
            ev(0, mask, 1 | 4, (init[0], init[1], rep[0], rep[1]), sid, f"Cast {sp_rows[spell]['name']}")
        # 50%: phase 1 (adds the other spells), with a fear/roar for melee bosses
        ph = e * 100 + 80
        scripts.append(dict(id=ph, delay=0, priority=0, command=44, datalong=1, datalong2=0, target_type=0, data_flags=0,
                            comments=f"{name} - Set Phase 1"))
        ev(2, 0, 0, (50, 0, 0, 0), ph, "Phase 1 at 50% HP")
        phases.append("50%: phase 2" + (" (adds " + ", ".join(sp_rows[s]["name"] for s in spells[2:]) + ")" if spells[2:] else ""))
        if not caster and FEAR in sp_rows and lvl >= 20:
            fs = e * 100 + 81
            cast(fs, FEAR)
            ev(0, 1, 1 | 4, (2000, 4000, 20000, 25000), fs, "Cast Intimidating Roar (phase 1)")
            phases[-1] += ", roar"
        en = e * 100 + 82
        cast(en, ENRAGE)
        ev(2, 0, 0, (25, 0, 0, 0), en, "Enrage at 25% HP")
        phases.append("25%: enrage")
        info.append(dict(id=e, name=name, level=lvl, where=zone,
                         spells=", ".join(f"{sp_rows[s]['name']} ({s}{', theirs' if s in au.SP else ''})" for s in spells),
                         phases="; ".join(phases)))
    return events, scripts, info


def cpp_list(au, boss_info):
    """The ten script uses that clearly need C++, ranked by how much content they gate."""
    got_ai = {b["id"] for b in boss_info}
    cands = []
    for r in au.rank_scripts():
        if r["kind"] != "creature" and not r["quests"]:
            continue
        blocked = [q for q in r["quests"] if au.res_after[q]["status"] == "broken"]
        r["blocked"] = blocked
        score = 10 * len(blocked) + 2 * len(r["quests"]) + (25 if r["tier"].startswith("2") else 0)
        if r["kind"] == "creature" and r["rank"] == 3:
            score += 25
        if "escort" in r["script"]:
            score += 15
        cands.append((score, r))
    cands.sort(key=lambda x: -x[0])
    out = []
    for score, r in cands[:10]:
        needs = []
        s = r["script"]
        if "escort" in s:
            needs.append("escort: waypoints, ambushes, quest credit on arrival")
        if s.startswith("boss_") or r["tier"].startswith("2"):
            needs.append("encounter: abilities, adds, phases, door/instance state")
            if r["id"] in got_ai:
                needs.append("(basic EventAI now in place as a stopgap)")
        if r["blocked"]:
            needs.append(f"quest logic: {len(r['blocked'])} hidden quest(s) depend on it (" + ", ".join(map(str, r["blocked"][:5]))
                         + f"), {len(r['quests'])} touch it")
        elif r["quests"]:
            needs.append(f"gossip/quest behaviour for {len(r['quests'])} quest(s) that work without it")
        if s.startswith("npc_") and not needs:
            needs.append("gossip/event behaviour")
        if s.startswith("go_") or r["kind"] == "gameobject":
            needs.append("object use handler (credit, summon or open)")
        if r["kind"] == "item":
            needs.append("item use handler (target check, credit or summon)")
        out.append(dict(what=f"{r['kind']} {r['id']} {r['name']} (`{s}`)", where=r["where"], needs="; ".join(needs)))
    return out
